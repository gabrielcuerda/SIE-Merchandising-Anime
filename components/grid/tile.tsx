import clsx from "clsx";
import Image from "next/image";
import Label from "../label";

export function GridTileImage({
  isInteractive = true,
  active,
  label,
  badge,
  ...props
}: {
  isInteractive?: boolean;
  active?: boolean;
  badge?: React.ReactNode;
  label?: {
    title: string;
    amount: string;
    currencyCode: string;
    position?: "bottom" | "center" | "bottom-center";
  };
} & React.ComponentProps<typeof Image>) {
  return (
    <div
      className={clsx(
        "group flex h-full w-full items-center justify-center overflow-hidden rounded-card border bg-white",
        {
          relative: Boolean(label || badge),
          "border-2 border-blue-600": active,
          "border-neutral-200 dark:border-neutral-800": !active,
        },
      )}
    >
      {props.src ? (
        <Image
          className={clsx("relative h-full w-full object-contain", {
            "transition duration-300 ease-in-out group-hover:scale-105":
              isInteractive,
          })}
          {...props}
        />
      ) : null}
      {badge ? <div className="absolute left-2 top-2 z-10">{badge}</div> : null}
      {label ? (
        <Label
          title={label.title}
          amount={label.amount}
          currencyCode={label.currencyCode}
          position={label.position}
        />
      ) : null}
    </div>
  );
}
